"""Markdown writing: documents and analysis reports."""

from __future__ import annotations

from pathlib import Path

from ..content import SECTION_BANK, detect_domain, topic_of, titlecase
from ..util import keywords, now_iso
from .registry import ToolContext, ToolResult, artifact


def _bullets_for(topic: str, domain: str) -> list[tuple[str, list[str]]]:
    bank = SECTION_BANK.get(domain) or SECTION_BANK["general"]
    kws = keywords(topic, 6) or [topic]
    out = []
    for section_title, bullets in bank[:5]:
        rendered = []
        for bullet in bullets:
            rendered.append(
                bullet.replace("{topic}", topic)
                .replace("{kw1}", kws[0])
                .replace("{kw2}", kws[1] if len(kws) > 1 else kws[0])
                .replace("{kw3}", kws[2] if len(kws) > 2 else kws[0])
            )
        out.append((section_title.replace("{topic}", topic), rendered))
    return out


def register(registry) -> None:
    @registry.tool(
        "report.write",
        "Write a structured markdown document or analysis report.",
        schema={
            "type": "object",
            "properties": {
                "path": {"type": "string"},
                "title": {"type": "string"},
                "request": {"type": "string"},
                "source_markdown": {"type": "string"},
                "sections": {
                    "type": "array",
                    "items": {
                        "type": "object",
                        "properties": {
                            "title": {"type": "string"},
                            "lines": {"type": "array", "items": {"type": "string"}},
                        },
                    },
                },
            },
            "required": ["path", "title"],
        },
        category="report",
    )
    def report_write(
        ctx: ToolContext,
        path: str,
        title: str,
        request: str = "",
        source_markdown: str = "",
        sections: list | None = None,
    ) -> ToolResult:
        target = ctx.path(path)
        lines = [f"# {title}", "", f"_Generated by QuanAI on {now_iso()}_", ""]

        if source_markdown:
            source = ctx.path(source_markdown)
            if not source.exists():
                raise FileNotFoundError(f"source report not found: {source_markdown}")
            body = source.read_text(encoding="utf-8", errors="replace").strip()
            if body.startswith("# "):
                body = body.split("\n", 1)[1].strip()
            lines += ["## Summary", "", body, ""]
        elif sections:
            for section in sections:
                heading = str(section.get("title", "Section"))
                lines += [f"## {heading}", ""]
                for item in section.get("lines", []):
                    lines.append(f"- {item}")
                lines.append("")
        else:
            topic = topic_of(request or title)
            domain = detect_domain(request or title)
            lines += [
                "## Purpose",
                "",
                f"This document explains {topic} and sets out a concrete way to act on it.",
                "",
            ]
            for heading, bullets in _bullets_for(topic, domain):
                lines += [f"## {heading}", ""] + [f"- {b}" for b in bullets] + [""]

        lines += [
            "## How this was produced",
            "",
            f"- Title: {titlecase(title)}",
            "- Method: local QuanAI pipeline; every claim above is derived from the request and the generated artifacts.",
            "- Related files live beside this document in the same workspace folder.",
            "",
            "## Open questions",
            "",
            "- Which audience matters most for the next revision?",
            "- What evidence would change the recommendation?",
            "",
        ]
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text("\n".join(lines), encoding="utf-8")
        return ToolResult.success(
            {"path": ctx.rel(target), "chars": target.stat().st_size, "headings": sum(1 for l in lines if l.startswith("#"))},
            [artifact(ctx, target, "report", "text/markdown")],
        )
