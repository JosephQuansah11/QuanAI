def _tokenise(text: str, plan: dict) -> str:
    name = plan["name"]
    return (
        text.replace("@NAME@", name)
        .replace("@SLUG@", plan["slug"])
        .replace("@DESC@", plan["description"].replace("\n", " "))
    )


def _short_name(name: str, limit: int = 12) -> str:
    """Keep a PWA short name readable instead of cutting mid-word."""
    if len(name) <= limit:
        return name
    first = re.match(r"^[A-Z][a-z]+", name)
    if first and 3 <= len(first.group(0)) <= limit:
        return first.group(0)
    return name[:limit]


def _icon(path: Path, size: int, name: str, accent: str = "#2563eb") -> Path:
    from PIL import Image, ImageDraw, ImageFont  # type: ignore

    image = Image.new("RGB", (size, size), (247, 248, 250))
    draw = ImageDraw.Draw(image)
    pad = size // 8
    draw.rounded_rectangle(
        [pad, pad, size - pad, size - pad], radius=size // 6, outline=accent, width=max(3, size // 42)
    )
    font = None
    for candidate in (
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf",
    ):
        if Path(candidate).exists():
            try:
                from PIL import ImageFont as _F  # noqa: F401

                font = _F.truetype(candidate, size // 2)
                break
            except OSError:
                continue
    if font is None:
        font = ImageFont.load_default()
    letter = (name[:1] or "Q").upper()
    box = draw.textbbox((0, 0), letter, font=font)
    draw.text(
        ((size - (box[2] - box[0])) / 2 - box[0], (size - (box[3] - box[1])) / 2 - box[1]),
        letter,
        font=font,
        fill=accent,
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, format="PNG")
    return path


def build_scaffold(
    root: Path,
    plan: dict,
    features_text: str,
) -> list[Path]:
    """Write every file for the chosen framework and return the paths."""
    framework = plan["framework"]
    written: list[Path] = []

    def write(relative: str, content: str) -> None:
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        written.append(target)

    if framework in {"tkinter", "pyqt6"}:
        template = TKINTER_MAIN if framework == "tkinter" else PYQT_MAIN
        write("main.py", template.substitute(name=plan["name"], description=plan["description"]))
        write("data.json", "[]\n")
        if framework == "pyqt6":
            write("requirements.txt", "PyQt6>=6.6\n")
        write(
            "run.sh",
            "#!/usr/bin/env bash\nset -e\ncd \"$(dirname \"$0\")\"\n"
            + ("python3 main.py\n" if framework == "tkinter" else "pip install -r requirements.txt && python3 main.py\n"),
        )
    elif framework == "electron":
        write("package.json", ELECTRON_PACKAGE.substitute(
            name=plan["name"], slug=plan["slug"], description=plan["description"]
        ))
        write("main.js", ELECTRON_MAIN.substitute(name=plan["name"], description=plan["description"]))
        write("preload.js", ELECTRON_PRELOAD.substitute(name=plan["name"], description=plan["description"]))
        write("renderer.js", RENDERER_JS.substitute(name=plan["name"], description=plan["description"]))
        write("index.html", HTML_APP.substitute(name=plan["name"], description=plan["description"]))
        write("styles.css", APP_CSS)
    elif framework == "pwa":
        write("index.html", HTML_APP.substitute(name=plan["name"], description=plan["description"]))
        write("styles.css", APP_CSS)
        write("app.js", PWA_APP_JS.substitute(name=plan["name"], slug=plan["slug"], description=plan["description"]))
        write("sw.js", SW_JS.substitute(name=plan["name"], slug=plan["slug"]))
        manifest = {
            "name": plan["name"],
            "short_name": _short_name(plan["name"]),
            "description": plan["description"],
            "start_url": "./index.html",
            "display": "standalone",
            "background_color": "#f7f8fa",
            "theme_color": "#2563eb",
            "icons": [
                {"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any maskable"},
                {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any maskable"},
            ],
        }
        write("manifest.webmanifest", json.dumps(manifest, indent=2) + "\n")
        written.append(_icon(root / "icons" / "icon-192.png", 192, plan["name"]))
        written.append(_icon(root / "icons" / "icon-512.png", 512, plan["name"]))
    elif framework == "flutter":
        write("pubspec.yaml", _tokenise(FLUTTER_PUBSPEC, plan))
        write("lib/main.dart", _tokenise(FLUTTER_MAIN, plan))
        write(
            "test/widget_test.dart",
            "// Smoke test for @NAME@\n".replace("@NAME@", plan["name"])
            + "import 'package:flutter_test/flutter_test.dart';\n"
            + "import 'package:" + plan["slug"] + "/main.dart';\n\n"
            + "void main() {\n  testWidgets('app renders', (tester) async {\n"
            + "    await tester.pumpWidget(const QuanApp());\n"
            + "    expect(find.text('" + plan["name"] + "'), findsWidgets);\n  });\n}\n",
        )
        write("analysis_options.yaml", "include: package:flutter_lints/flutter.yaml\n")
    elif framework == "react-native":
        write("package.json", _tokenise(RN_PACKAGE, plan))
        write("App.js", _tokenise(RN_APP, plan))
        write("app.json", _tokenise(RN_APP_JSON, plan))
        write("babel.config.js", RN_BABEL)
    else:
        raise ToolError(f"unknown framework: {framework}")

    write(
        "README.md",
        README.substitute(
            name=plan["name"],
            description=plan["description"],
            run=plan["run"],
            features=features_text,
            stack=plan["framework_label"],
            framework_label=plan["framework_label"],
        ),
    )
    return written

