def register(registry) -> None:
    @registry.tool(
        "app.scaffold",
        "Generate a runnable desktop or mobile application from a description.",
        schema=SCHEMA,
        category="apps",
        requires=["pillow"],
    )
    def app_scaffold(
        ctx: ToolContext,
        path: str,
        description: str,
        name: str = "",
        platform: str = "desktop",
        framework: str = "",
    ) -> ToolResult:
        plan = app_plan(description, platform, framework or None)
        if name:
            plan["name"] = name
            plan["slug"] = name.lower().replace(" ", "-")
        root = ctx.path(path)
        root.mkdir(parents=True, exist_ok=True)
        features_text = "\n".join(
            f"- **{feature['title']}** - {feature['detail']}" for feature in plan["features"]
        )
        written = build_scaffold(root, plan, features_text)
        return ToolResult.success(
            {
                "path": ctx.rel(root),
                "framework": plan["framework"],
                "framework_label": plan["framework_label"],
                "platform": plan["platform"],
                "run": plan["run"],
                "files": [ctx.rel(p) for p in written],
                "file_count": len(written),
                "features": [f["title"] for f in plan["features"]],
            },
            [
                artifact(
                    ctx, root, "app", "application/x-directory",
                    framework=plan["framework"], files=len(written),
                )
            ],
        )

    @registry.tool(
        "app.frameworks",
        "List the desktop and mobile frameworks QuanAI can scaffold.",
        schema={"type": "object", "properties": {}, "required": []},
        category="apps",
    )
    def app_frameworks(ctx: ToolContext) -> ToolResult:
        import shutil

        available = {
            "python": bool(shutil.which("python3")),
            "node": bool(shutil.which("node")),
            "flutter": bool(shutil.which("flutter")),
        }
        payload = {}
        for platform, options in FRAMEWORKS.items():
            payload[platform] = {}
            for key, value in options.items():
                needs = value.get("requires", [])
                ready = all(available.get(need.lower(), bool(shutil.which(need))) for need in needs)
                if not needs:
                    ready = True
                payload[platform][key] = {**value, "ready": ready}
        return ToolResult.success({"platforms": payload, "tools": available})
